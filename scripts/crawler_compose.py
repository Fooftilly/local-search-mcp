"""Explicitly generate a private, non-destructive Crawl4AI Compose scaffold.

The generator never runs Docker Compose, changes a running container, installs a
firewall or modifies the operator's separate Compose projects.
"""
from __future__ import annotations

import os
from pathlib import Path
import re
import stat
import subprocess

COMPOSE_YAML = """# Generated by local-search-mcp -- never a live migration.
# Review existing Crawl4AI volumes, env and image before deploying.
name: local-search-crawler
services:
  crawl4ai:
    image: ${CRAWL4AI_IMAGE:?Set a verified Crawl4AI 0.9.5+ image}
    container_name: crawl4ai
    restart: unless-stopped
    shm_size: 1gb
    ports:
      - "127.0.0.1:11235:11235"
    environment:
      CRAWL4AI_API_TOKEN: ${CRAWL4AI_API_TOKEN:?Crawl4AI API token required}
    dns:
      - 1.1.1.1
      - 9.9.9.9
    networks:
      - crawler-egress
networks:
  crawler-egress:
    driver: bridge
    enable_ipv6: false
"""
_IMAGE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._:/@-]{0,254}\Z")
_NOFOLLOW = getattr(os, "O_NOFOLLOW", 0)


class ComposeSetupError(ValueError):
    """Cannot safely generate a new private Compose installation."""


def inspect_existing_image() -> str:
    """Read only the current crawler's image tag, without accessing its env."""
    try:
        response = subprocess.run(
            ["docker", "inspect", "--type=container", "--format", "{{.Config.Image}}",
             "crawl4ai"], capture_output=True, text=True, check=False, timeout=8,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise ComposeSetupError("Cannot inspect current image; supply --crawler-image") from exc
    if response.returncode != 0:
        raise ComposeSetupError("No existing crawl4ai container; supply --crawler-image")
    return validate_image(response.stdout.strip())


def validate_image(image: str) -> str:
    """Accept only an explicit image reference, never shell/YAML metacharacters."""
    if not isinstance(image, str) or not _IMAGE.fullmatch(image):
        raise ComposeSetupError("Invalid Docker image; supply a verified Crawl4AI image reference")
    if image.startswith(("/", ".", "-")) or ".." in image or "//" in image:
        raise ComposeSetupError("Invalid Docker image reference")
    return image


def _env_literal(value: str) -> str:
    """Compose single-quoted .env values prevent $ interpolation and comments."""
    if not value or any(ord(c) < 32 or ord(c) == 127 for c in value):
        raise ComposeSetupError("API token contains unsupported control characters")
    # Compose supports \' for embedded single quotes. Avoid ambiguous backslash
    # sequences rather than generating a token that might change on parsing.
    if "\\" in value:
        raise ComposeSetupError("API token contains unsupported backslashes")
    return "'" + value.replace("'", "\\'") + "'"


def _write_exclusive(path: Path, payload: str) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | _NOFOLLOW, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as output:
        output.write(payload)
        output.flush()
        os.fsync(output.fileno())


def generate(private_dir: Path, *, image: str, token: str) -> Path:
    """Create an owner-only new project, never editing existing Compose projects."""
    image = validate_image(image)
    quoted_image = _env_literal(image)
    quoted_token = _env_literal(token)
    if (private_dir.is_symlink() or not private_dir.is_dir()
            or private_dir.stat().st_uid != os.getuid()
            or not stat.S_ISDIR(private_dir.stat().st_mode)
            or private_dir.stat().st_mode & 0o077):
        raise ComposeSetupError("Private settings directory must be owner-only mode 0700")
    target = private_dir / "crawler-compose"
    if target.exists() or target.is_symlink():
        raise ComposeSetupError("Crawler Compose directory already exists; refusing to overwrite")
    try:
        target.mkdir(mode=0o700)
    except FileExistsError as exc:
        raise ComposeSetupError("Crawler Compose directory already exists") from exc
    try:
        _write_exclusive(target / "compose.yaml", COMPOSE_YAML)
        _write_exclusive(target / ".env",
                         "CRAWL4AI_IMAGE=" + quoted_image + "\n"
                         "CRAWL4AI_API_TOKEN=" + quoted_token + "\n")
        fd = os.open(target, os.O_RDONLY | os.O_DIRECTORY | _NOFOLLOW)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)
    except BaseException:
        # Only remove files this invocation created inside its new directory.
        for name in ("compose.yaml", ".env"):
            file = target / name
            if file.is_file() and not file.is_symlink():
                file.unlink()
        target.rmdir()
        raise
    return target
