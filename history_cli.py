#!/usr/bin/env python3
"""Read/filter/export the local search MCP JSONL history (no extra dependencies)."""
from __future__ import annotations

import argparse
import csv
from datetime import date
from collections import Counter, deque
import json
from pathlib import Path
import sys
import unicodedata

from history_log import history_path


def safe_terminal(value: object) -> str:
    """Make untrusted history inert in terminals, including bidi overrides."""
    out = []
    for char in str(value):
        if unicodedata.category(char) in ("Cc", "Cf", "Cs", "Zl", "Zp"):
            code = ord(char)
            out.append(f"\\x{code:02x}" if code <= 0xff else f"\\u{code:04x}")
        else:
            out.append(char)
    return "".join(out)


def safe_csv_cell(value: object) -> object:
    """Keep CSV safe for both spreadsheet imports and terminal inspection."""
    if not isinstance(value, str):
        return value
    # Some spreadsheet importers ignore leading Unicode whitespace before
    # evaluating formulas. Check the original before escaping controls.
    formula = bool(value) and (
        value[0] in "=+-@\t\r\n" or value.lstrip()[:1] in "=+-@"
    )
    value = safe_terminal(value)
    return ("'" if formula else "") + value


def events(path: Path):
    if not path.exists():
        return
    with path.open(encoding="utf-8") as stream:
        for row in stream:
            try:
                event = json.loads(row)
            except json.JSONDecodeError:
                continue
            if isinstance(event, dict):
                if event.get("kind") == "page":
                    safe_action = event.get("action") if event.get("action") in ("find", "section", "links_page", "compare") else None
                    # Page handles are bearer capabilities. Even a malformed
                    # or legacy history row must not leak one through --json.
                    safe_fields = ("time_utc", "kind", "backend", "status",
                                   "page", "page_count", "duration_ms",
                                   "error_type", "http_status")
                    event = {key: event[key] for key in safe_fields if key in event}
                    # Only a literal marker generated by our trusted audit
                    # decorator may distinguish a find; never copy arbitrary
                    # action strings from legacy or malformed JSONL rows.
                    if safe_action:
                        event["action"] = safe_action
                yield event


def main() -> int:
    parser = argparse.ArgumentParser(description="Show/export web_search, web_fetch and continuation-page history")
    parser.add_argument("--last", type=int, default=30, help="Number of newest entries (default: 30)")
    parser.add_argument("--kind", choices=["search", "fetch", "page"], help="Only one kind of call")
    parser.add_argument("--status", choices=["success", "error", "pending", "denied", "blocked", "expired_or_unknown"], help="Filter by outcome")
    parser.add_argument("--since", type=date.fromisoformat, help="Include entries on or after YYYY-MM-DD (UTC)")
    parser.add_argument("--json", action="store_true", help="Print JSON events (page handles and text omitted)")
    parser.add_argument("--csv", action="store_true", help="Print filtered events as CSV")
    parser.add_argument("--stats", action="store_true", help="Print event counts instead of records")
    args = parser.parse_args()
    if args.last < 1 or args.last > 100_000:
        parser.error("--last must be between 1 and 100000")
    path = history_path()
    if not path.exists():
        print(f"No history yet: {safe_terminal(path)}", file=sys.stderr)
        return 0

    def matches(event):
        return ((not args.kind or event.get("kind") == args.kind)
                and (not args.status or event.get("status") == args.status)
                and (not args.since or event.get("time_utc", "")[:10] >= args.since.isoformat()))

    selected = (e for e in events(path) if matches(e))
    if args.stats:
        # History may contain legacy or malformed JSON values (including
        # unhashable lists/dicts). Sanitize to strings before counting/sorting.
        counter = Counter((safe_terminal(e.get("kind") or "?"),
                           safe_terminal(e.get("status") or "?"))
                          for e in selected)
        print(f"History file: {safe_terminal(path)}")
        for (kind, status), total in sorted(counter.items()):
            print(f"{kind:6} {status:7} {total}")
        return 0
    recent = list(deque(selected, maxlen=args.last))
    if args.csv:
        writer = csv.DictWriter(sys.stdout, fieldnames=["time_utc", "kind", "status", "action", "query", "url", "result_count", "page", "page_count", "http_status", "duration_ms"])
        writer.writeheader()
        for e in recent:
            writer.writerow({name: safe_csv_cell(e.get(name, "")) for name in writer.fieldnames})
    elif args.json:
        for e in recent:
            print(json.dumps(e, ensure_ascii=True))
    else:
        print(f"History: {safe_terminal(path)}")
        for e in recent:
            term = e.get("query") if e.get("kind") == "search" else e.get("url", "")
            if e.get("kind") == "page":
                if e.get("action") == "find":
                    term = f"find in temporary document ({e.get('page_count') or '?'} pages)"
                elif e.get("action") == "section":
                    term = "section of temporary document"
                elif e.get("action") == "links_page":
                    term = "links of temporary document"
                elif e.get("action") == "compare":
                    term = "comparison of temporary documents"
                else:
                    term = f"page {e.get('page', '?')}/{e.get('page_count') or '?'}"
            count = f" | {e['result_count']} results" if "result_count" in e else ""
            status = e.get("status", "?")
            http = f" | HTTP {e['http_status']}" if "http_status" in e else ""
            print(f"{safe_terminal(e.get('time_utc', '?'))} | "
                  f"{safe_terminal(e.get('kind', '?')):6} | "
                  f"{safe_terminal(status):7} | {safe_terminal(term)}"
                  f"{safe_terminal(count)}{safe_terminal(http)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
